from datetime import datetime
from typing import Protocol

from app.domain.models import (
    ActionPlan,
    Alert,
    AnomalyResult,
    Asset,
    AuditEntry,
    Evidence,
    FeatureWindow,
    GroundedAnswer,
    MaintenanceFact,
    Task,
    WeatherEvent,
)


class AssetReader(Protocol):
    """Read asset and maintenance facts without exposing storage details."""

    def assets(self) -> list[Asset]: ...
    def asset(self, asset_id: str) -> Asset | None: ...
    def maintenance(self, asset_id: str) -> list[MaintenanceFact]: ...


class EventStore(Protocol):
    """Read and save weather warnings."""

    def event(self, event_id: str) -> WeatherEvent | None: ...
    def events(self) -> list[WeatherEvent]: ...
    def save_event(self, event: WeatherEvent) -> None: ...


class AlertStore(Protocol):
    """Read, deduplicate and save weather or condition alerts."""

    def alert(self, alert_id: str) -> Alert | None: ...
    def alerts(self, asset_id: str | None = None) -> list[Alert]: ...
    def by_dedupe_key(self, key: str) -> Alert | None: ...
    def save_alert(self, alert: Alert) -> None: ...


class WorkStore(Protocol):
    """Persist plans, response tasks and the decision audit trail."""

    def plan(self, plan_id: str) -> ActionPlan | None: ...
    def plans(self) -> list[ActionPlan]: ...
    def save_plan(self, plan: ActionPlan) -> None: ...
    def tasks(self, asset_id: str | None = None) -> list[Task]: ...
    def task(self, task_id: str) -> Task | None: ...
    def save_task(self, task: Task) -> None: ...
    def add_audit(self, entry: AuditEntry) -> None: ...
    def audit(self) -> list[AuditEntry]: ...


class ObservationStore(Protocol):
    """Store per-window model results for replay checks and persistence rules."""

    def observation(self, asset_id: str, at: datetime, version: str) -> AnomalyResult | None: ...
    def observations(self, asset_id: str) -> list[AnomalyResult]: ...
    def save_observation(self, result: AnomalyResult) -> None: ...


class AnomalyDetector(Protocol):
    def evaluate(self, window: FeatureWindow) -> AnomalyResult: ...
    def info(self) -> dict: ...


class Retriever(Protocol):
    def retrieve(self, query: str, hazard: str, asset_type: str) -> list[Evidence]: ...


class AnswerGenerator(Protocol):
    mode: str

    def generate(
        self, question: str, context: dict, evidence: list[Evidence]
    ) -> GroundedAnswer: ...
